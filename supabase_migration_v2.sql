create policy "customers read own order items" on public.order_items for select to authenticated using (exists(select 1 from public.orders o where o.id=order_id and (o.user_id=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'))));
create policy "customers read own shipping events" on public.shipping_events for select to authenticated using (exists(select 1 from public.orders o where o.id=order_id and (o.user_id=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'))));
create policy "admin manage shipping" on public.shipping_events for all to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin')) with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

create policy "customers manage own favorites" on public.favorites for all to authenticated using (user_id=auth.uid()) with check (user_id=auth.uid());
create policy "public read active coupons" on public.coupons for select to anon,authenticated using (active=true and (expires_at is null or expires_at>now()));
create policy "customers read reviews" on public.reviews for select to anon,authenticated using (true);
create policy "customers write reviews" on public.reviews for insert to authenticated with check (user_id=auth.uid());
create policy "public read site settings" on public.site_settings for select to anon,authenticated using (true);
create policy "admin manage site settings" on public.site_settings for all to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin')) with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

-- وظيفة آمنة لإنشاء الطلب مع عناصره. تمنع العميل من إنشاء طلب باسم مستخدم آخر.
drop function if exists public.create_order_with_items(jsonb,jsonb);
create or replace function public.create_order_with_items(p_order jsonb,p_items jsonb)
returns table(id uuid,order_number text,tracking_number text,total numeric,status text)
language plpgsql security definer set search_path=public
as $$
declare
  v_order_id uuid;
  v_order_number text;
  v_tracking text;
  v_item jsonb;
  v_user uuid:=auth.uid();
  v_total numeric:=coalesce((p_order->>'total')::numeric,0);
  v_subtotal numeric:=coalesce((p_order->>'subtotal')::numeric,0);
  v_discount numeric:=coalesce((p_order->>'discount')::numeric,0);
  v_product_id bigint;
  v_qty integer;
  v_price numeric;
  v_stock integer;
begin
  if v_user is null then raise exception 'يجب تسجيل الدخول أولًا'; end if;
  if coalesce(jsonb_array_length(p_items),0)=0 then raise exception 'السلة فارغة'; end if;
  v_order_number:='FRK-'||to_char(now(),'YYYYMMDD')||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));
  v_tracking:='FRKTRK-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,10));
  insert into public.orders(order_number,tracking_number,user_id,subtotal,discount,total,status,payment_status,payment_method,shipping_name,shipping_phone,shipping_address,shipping_city,customer_note)
  values(v_order_number,v_tracking,v_user,v_subtotal,v_discount,v_total,coalesce(p_order->>'status','pending_payment'),'pending',coalesce(p_order->>'payment_method','card'),coalesce(p_order->>'shipping_name',''),coalesce(p_order->>'shipping_phone',''),coalesce(p_order->>'shipping_address',''),p_order->>'shipping_city',p_order->>'customer_note') returning orders.id into v_order_id;
  for v_item in select * from jsonb_array_elements(p_items) loop
    v_product_id:=(v_item->>'product_id')::bigint; v_qty:=(v_item->>'quantity')::integer; v_price:=(v_item->>'unit_price')::numeric;
    select stock into v_stock from public.products where products.id=v_product_id for update;
    if not found then raise exception 'المنتج غير موجود'; end if;
    if v_stock < v_qty then raise exception 'المخزون غير كافٍ للمنتج %',(v_item->>'name'); end if;
    insert into public.order_items(order_id,product_id,product_name,quantity,unit_price) values(v_order_id,v_product_id,coalesce(v_item->>'name','منتج'),v_qty,v_price);
    update public.products set stock=stock-v_qty where products.id=v_product_id;
  end loop;
  insert into public.shipping_events(order_id,status,note) values(v_order_id,'pending_payment','تم إنشاء الطلب');
  return query select o.id,o.order_number,o.tracking_number,o.total,o.status from public.orders o where o.id=v_order_id;
end; $$;
revoke all on function public.create_order_with_items(jsonb,jsonb) from public;
grant execute on function public.create_order_with_items(jsonb,jsonb) to authenticated;

